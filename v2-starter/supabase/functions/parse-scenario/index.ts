// ── Minimal per-IP rate limiting ──────────────────────────────────────────
// In-memory only: resets on cold start and is not shared across instances.
// Good enough to blunt casual abuse; replace with a durable store (e.g. a
// Supabase table or Upstash) if real abuse shows up in telemetry.
const RATE_LIMIT_WINDOW_MS = 60_000;
const RATE_LIMIT_MAX_REQUESTS = 20;
/** @type {Map<string, { count: number, windowStart: number }>} */
const rateLimitState = new Map();

function isRateLimited(ip) {
  const now = Date.now();
  const entry = rateLimitState.get(ip);
  if (!entry || now - entry.windowStart > RATE_LIMIT_WINDOW_MS) {
    rateLimitState.set(ip, { count: 1, windowStart: now });
    return false;
  }
  entry.count += 1;
  return entry.count > RATE_LIMIT_MAX_REQUESTS;
}

function getClientIp(req) {
  return (
    req.headers.get('x-forwarded-for')?.split(',')[0]?.trim() ??
    req.headers.get('cf-connecting-ip') ??
    req.headers.get('x-real-ip') ??
    'unknown'
  );
}

